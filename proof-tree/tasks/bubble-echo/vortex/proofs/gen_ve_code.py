#!/usr/bin/env python3
"""Generate the code-binding files of the Vortex Echo v1 leaves on vortex/core/ve_core.wasm: each export body bound by
define_assert_from_wasm (which re-reads the module file and checks the bytes when the leaf loads), and its decode table
(FAST_MK_EXEC_RULE for a short body, the windowed FAST_MK_EXEC_RANGES of onefilm2/proofs/of2_dec.ml over a pc range
otherwise). The bytes are read from the module, never typed by hand.
  ve_drop_code.ml  droplet pair (PARKED leaf)
  ve_vort_code.ml  vortex Fredkin pair (decode window: the Fredkin loop from pc 1305 to the end)
  ve_tick_code.ml  header tick increment / decrement
  ve_vk_code.ml    decode windows of the vortex pair's field phase (pc 21 .. 1305) over the bindings of ve_vort_code.ml
Usage: gen_ve_code.py [--check]"""
import hashlib, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
BE = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, os.path.join(BE, 'core'))
import wasm_check as W  # noqa: E402

MODULE = os.path.join(HERE, '..', 'core', 've_core.wasm')
# file -> (extra needs, [(constant, export, exec name, decode range or None)])
FILES = {
    've_drop_code.ml': ([], [('ve_drop_apply_mc', 've_drop_apply', 'VE_DROP_APPLY_EXEC', None),
                             ('ve_drop_unapply_mc', 've_drop_unapply', 'VE_DROP_UNAPPLY_EXEC', None)]),
    've_vort_code.ml': (['../../onefilm2/proofs/of2_dec.ml'],
                        [('ve_vort_apply_mc', 've_vort_apply', 'VE_VORT_APPLY_EXEC', 1305),
                         ('ve_vort_unapply_mc', 've_vort_unapply', 'VE_VORT_UNAPPLY_EXEC', 1305)]),
    've_tick_code.ml': ([], [('ve_tick_inc_mc', 've_tick_inc', 'VE_TICK_INC_EXEC', None),
                             ('ve_tick_dec_mc', 've_tick_dec', 'VE_TICK_DEC_EXEC', None)]),
}
# decode-only files: windows over bodies already bound in another generated file (no second binding)
WINDOWS = {
    've_vk_code.ml': ('ve_vort_code.ml', [('ve_vort_apply_mc', 've_vort_apply', 'VE_VK_APPLY_EXEC'),
                                          ('ve_vort_unapply_mc', 've_vort_unapply', 'VE_VK_UNAPPLY_EXEC')]),
}


def body(data, export):
    mod = W.parse(data)
    code = mod['codes'][mod['exports'][export][1]]
    r = W.R(code)
    for _ in range(r.uleb()):
        r.uleb()
        r.byte()
    return code, r.p          # body bytes (local declarations first) and the pc of the first instruction


def gen_file(extra, exports):
    data = open(MODULE, 'rb').read()
    out = ['(* GENERATED by vortex/proofs/gen_ve_code.py from vortex/core/ve_core.wasm (sha256 %s); do not edit. *)'
           % hashlib.sha256(data).hexdigest(),
           '(* Export bodies bound to their Code-section entries; dependency only, proves no claim. *)',
           '', 'needs "wasm/proofs/wasm_tactics.ml";;', 'needs "../../capillary/proofs/wasm_fastdec.ml";;']
    out += ['needs "%s";;' % e for e in extra] + ['']
    for name, exp, ex, lo in exports:
        code, pc0 = body(data, exp)
        hexs = ['0x%02x' % b for b in code]
        lines = ['   ' + '; '.join(hexs[i:i + 12]) for i in range(0, len(hexs), 12)]
        out.append('let %s = define_assert_from_wasm "%s"\n  "../core/ve_core.wasm" "%s"\n  [%s];;\n'
                   % (name, name, exp, (';\n'.join(lines)).strip()))
        if lo is None:
            out.append('let %s = FAST_MK_EXEC_RULE %s %d;;\n' % (ex, name, pc0))
        else:
            out.append('let %s = FAST_MK_EXEC_RANGES %s [%d, %d];;\n' % (ex, name, lo, len(code)))
    return '\n'.join(out)


def gen_window(dep, exports):
    data = open(MODULE, 'rb').read()
    out = ['(* GENERATED by vortex/proofs/gen_ve_code.py from vortex/core/ve_core.wasm (sha256 %s); do not edit. *)'
           % hashlib.sha256(data).hexdigest(),
           '(* Decode windows of the field phase: from the first instruction (wasm_entry, after the local         *)',
           '(* declarations) to pc 1305, the start of the Fredkin loop. Dependency only, proves no claim.         *)',
           '', 'needs "%s";;' % dep, '']
    for name, exp, ex in exports:
        code, pc0 = body(data, exp)
        out.append('let %s = FAST_MK_EXEC_RANGES %s [%d, 1305];;\n' % (ex, name, pc0))
    return '\n'.join(out)


def bodies():
    data = open(MODULE, 'rb').read()
    return {name: body(data, exp)[0] for _, (_, exps) in FILES.items() for name, exp, _, _ in exps}


if __name__ == '__main__':
    bad = []
    for f, (extra, exps) in FILES.items():
        t = gen_file(extra, exps)
        path = os.path.join(HERE, f)
        if '--check' in sys.argv:
            if not os.path.exists(path) or open(path).read() != t:
                bad.append(f)
        else:
            open(path, 'w').write(t); print('wrote', f)
    for f, (dep, exps) in WINDOWS.items():
        t = gen_window(dep, exps)
        path = os.path.join(HERE, f)
        if '--check' in sys.argv:
            if not os.path.exists(path) or open(path).read() != t:
                bad.append(f)
        else:
            open(path, 'w').write(t); print('wrote', f)
    if '--check' in sys.argv:
        print('DIFFERS: ' + ' '.join(bad) if bad else 'OK'); sys.exit(1 if bad else 0)
