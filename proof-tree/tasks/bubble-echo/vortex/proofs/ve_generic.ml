    ASM_CASES_TAC `ve_t s + 1 = ve_pt s` THENL
     [REWRITE_TAC[VE_FRAME_TP] THEN
      SUBGOAL_THEN `~(ve_t s + 1 < ve_pt s)` (fun th -> REWRITE_TAC[th]) THENL [ASM_ARITH_TAC; ALL_TAC] THEN
