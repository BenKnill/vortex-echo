   (!a b c d e f g h i j. ve_pt (a,b,c,d,e,f,g,h,i,j) = b) /\
   (!a b c d e f g h i j. ve_va (a,b,c,d,e,f,g,h,i,j) = c) /\
   (!a b c d e f g h i j. ve_vb (a,b,c,d,e,f,g,h,i,j) = d) /\
   (!a b c d e f g h i j. ve_hm (a,b,c,d,e,f,g,h,i,j) = e) /\
   (!a b c d e f g h i j. ve_ra (a,b,c,d,e,f,g,h,i,j) = f) /\
   (!a b c d e f g h i j. ve_rb (a,b,c,d,e,f,g,h,i,j) = g) /\
