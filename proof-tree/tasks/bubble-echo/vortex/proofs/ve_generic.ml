let VE_FRAME_TP = prove
 (`(!fr x. ve_t (ve_rim_fwd fr x) = ve_t x /\ ve_pt (ve_rim_fwd fr x) = ve_pt x) /\
   (!kj dj x. ve_t (ve_jig_fwd kj dj x) = ve_t x /\ ve_pt (ve_jig_fwd kj dj x) = ve_pt x) /\
   (!kc dc nc x. ve_t (ve_corr_fwd kc dc nc x) = ve_t x /\ ve_pt (ve_corr_fwd kc dc nc x) = ve_pt x) /\
   (!kd dd x. ve_t (ve_drop_fwd kd dd x) = ve_t x /\ ve_pt (ve_drop_fwd kd dd x) = ve_pt x) /\
   (!bf x. ve_t (ve_birth_fwd bf x) = ve_t x /\ ve_pt (ve_birth_fwd bf x) = ve_pt x) /\
   (!fv n x. ve_t (ve_vort_fwd fv n x) = ve_t x /\ ve_pt (ve_vort_fwd fv n x) = ve_pt x) /\
   (!x. ve_t (ve_tick_fwd x) = ve_t x + 1 /\ ve_pt (ve_tick_fwd x) = ve_pt x) /\
   (!i0 x. ve_t (ve_punct i0 x) = ve_t x /\ ve_pt (ve_punct i0 x) = ve_pt x)`,
  REWRITE_TAC[ve_rim_fwd; ve_jig_fwd; ve_corr_fwd; ve_drop_fwd; ve_birth_fwd; ve_vort_fwd;
              ve_tick_fwd; ve_punct; LET_DEF; LET_END_DEF] THEN
  VE_BETA_TAC THEN REWRITE_TAC[VE_W_ACC] THEN
  REPEAT STRIP_TAC THEN TRY COND_CASES_TAC THEN ASM_REWRITE_TAC[VE_W_ACC]);;

let VE_FRAME_BS = prove
 (`(!fr x. ve_bs (ve_rim_fwd fr x) = ve_bs x) /\
   (!kj dj x. ve_bs (ve_jig_fwd kj dj x) = ve_bs x) /\
   (!fv n x. ve_bs (ve_vort_fwd fv n x) = ve_bs x) /\
   (!x. ve_bs (ve_tick_fwd x) = ve_bs x) /\
   (!bf x. ve_bs (ve_birth_fwd bf x) = ve_push (ve_t x) (bf x) (ve_bs x))`,
  REWRITE_TAC[ve_rim_fwd; ve_jig_fwd; ve_vort_fwd; ve_tick_fwd; ve_birth_fwd; LET_DEF; LET_END_DEF] THEN
  VE_BETA_TAC THEN REWRITE_TAC[VE_W_ACC]);;

