(* ========================================================================= *)
(* Vortex Echo v1 (tasks/bubble-echo/vortex): the reversible tick at model   *)
(* level, pure HOL (no bytes). Definitions in ve_generic_defs.ml; statement  *)
(* texts generated by gen_ve_spec.py (ve_generic_stmts.ml, ve_generic.spec). *)
(*                                                                           *)
(* 1. FREDKIN_STEP_INVERSE / FREDKIN_STEPS_INVERSE (+ the converses): the    *)
(*    Fredkin pair step (a,b) -> (b, a + f b) for any f, one and n substeps. *)
(* 2. KICK_DRIFT_INVERSE / KICK_DRIFT_STEPS_INVERSE (+ converses).           *)
(* 3. VE_COMPOSE_INVERSE: the backbone of the whole-tick inverse.            *)
(* 4. LIFO_BIRTHS_INVERSE / VE_PUSH_INVERSE under the named premise          *)
(*    ve_log_ok; VE_LOG_OK_PUSH (the premise holds again after the births).  *)
(* 5. VE_STEP_INVERSE_MODEL (+ _V1: 4 corrugation substeps, 16 vortex        *)
(*    substeps per swirl tick, 1 per pop tick) under the named premise       *)
(*    ve_step_ok; VE_RUN_INVERSE_MODEL over n ticks under the invariant      *)
(*    ve_run_ok, kept by every forward tick (VE_RUN_OK_STEP) and true at the  *)
(*    start (VE_RUN_OK_INIT).                                                *)
(* ========================================================================= *)

