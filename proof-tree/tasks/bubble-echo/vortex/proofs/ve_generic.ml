let VE_BS_ACC = prove
 (`(!a b c d e f. ve_zq (a,b,c,d,e,f) = a) /\ (!a b c d e f. ve_zp (a,b,c,d,e,f) = b) /\
   (!a b c d e f. ve_dq (a,b,c,d,e,f) = c) /\ (!a b c d e f. ve_dp (a,b,c,d,e,f) = d) /\
   (!a b c d e f. ve_cnt (a,b,c,d,e,f) = e) /\ (!a b c d e f. ve_slots (a,b,c,d,e,f) = f)`,
  REWRITE_TAC[ve_zq; ve_zp; ve_dq; ve_dp; ve_cnt; ve_slots; FST; SND]);;

let VE_BS_ETA = prove
 (`!s. (ve_zq s,ve_zp s,ve_dq s,ve_dp s,ve_cnt s,ve_slots s) = s`,
  REWRITE_TAC[ve_zq; ve_zp; ve_dq; ve_dp; ve_cnt; ve_slots; PAIR]);;

let VE_PUSH1_CNT = prove
 (`!t b s. ve_cnt (ve_push1 t b s) = ve_cnt s + 1`,
  REWRITE_TAC[ve_push1; LET_DEF; LET_END_DEF] THEN VE_BETA_TAC THEN
  REWRITE_TAC[VE_BS_ACC]);;

let VE_PUSH1_TOP = prove
 (`!t b s. ve_rbirth (ve_slots (ve_push1 t b s) (ve_cnt s)) = t + 1`,
  REWRITE_TAC[ve_push1; LET_DEF; LET_END_DEF] THEN VE_BETA_TAC THEN
  REWRITE_TAC[VE_BS_ACC] THEN VE_BETA_TAC THEN REWRITE_TAC[ve_rbirth; FST; SND]);;

let VE_FREE_PUSH1 = prove
 (`!t b s. ve_free s ==> ve_free (ve_push1 t b s)`,
  REPEAT GEN_TAC THEN REWRITE_TAC[ve_free; ve_push1; LET_DEF; LET_END_DEF] THEN
  VE_BETA_TAC THEN REWRITE_TAC[VE_BS_ACC] THEN VE_BETA_TAC THEN
  STRIP_TAC THEN CONJ_TAC THEN X_GEN_TAC `i:num` THEN DISCH_TAC THENL
   [COND_CASES_TAC THENL
     [SUBGOAL_THEN `F` CONTR_TAC THEN ASM_ARITH_TAC;
      FIRST_X_ASSUM(fun th -> MATCH_MP_TAC th THEN ASM_ARITH_TAC)];
    SUBGOAL_THEN `~(3 * ve_cnt s <= i /\ i < 3 * ve_cnt s + 3)` (fun th -> REWRITE_TAC[th]) THENL
     [ASM_ARITH_TAC;
      ASM_MESON_TAC[ARITH_RULE `3 * (c + 1) <= i ==> 3 * c <= i`]]]);;

let VE_POP_PUSH1 = prove
 (`!t b s. ve_free s ==> ve_pop1 (ve_push1 t b s) = s`,
  REPEAT GEN_TAC THEN REWRITE_TAC[ve_free] THEN STRIP_TAC THEN
  REWRITE_TAC[ve_pop1; ve_push1; LET_DEF; LET_END_DEF] THEN VE_BETA_TAC THEN
  REWRITE_TAC[VE_BS_ACC; ADD_SUB] THEN VE_BETA_TAC THEN REWRITE_TAC[FST; SND] THEN
  GEN_REWRITE_TAC RAND_CONV [GSYM VE_BS_ETA] THEN
  REWRITE_TAC[PAIR_EQ; FUN_EQ_THM] THEN REPEAT CONJ_TAC THEN X_GEN_TAC `i:num` THEN
  REPEAT COND_CASES_TAC THEN ASM_REWRITE_TAC[VE_WSUB_ADD] THEN ASM_MESON_TAC[LE_REFL]);;

let VE_PUSH_CNT = prove
 (`!t L s. ve_cnt (ve_push t L s) = ve_cnt s + LENGTH L`,
  GEN_TAC THEN LIST_INDUCT_TAC THEN
  ASM_REWRITE_TAC[ve_push; LENGTH; ADD_CLAUSES; VE_PUSH1_CNT] THEN ARITH_TAC);;

let VE_FREE_PUSH = prove
 (`!t L s. ve_free s ==> ve_free (ve_push t L s)`,
  GEN_TAC THEN LIST_INDUCT_TAC THEN ASM_SIMP_TAC[ve_push; VE_FREE_PUSH1]);;

let VE_UNB_PUSH = prove
 (`!t L s n. ve_free s ==> ve_unb (t + 1) (n + LENGTH L) (ve_push t L s) = ve_unb (t + 1) n s`,
  GEN_TAC THEN LIST_INDUCT_TAC THEN REWRITE_TAC[ve_push; LENGTH; ADD_CLAUSES] THEN
  REPEAT STRIP_TAC THEN
  REWRITE_TAC[ARITH_RULE `SUC(n + l) = SUC n + l`] THEN
  ASM_SIMP_TAC[VE_FREE_PUSH1] THEN
  REWRITE_TAC[ve_unb; VE_PUSH1_CNT; ADD_SUB; VE_PUSH1_TOP; ARITH_RULE `0 < n + 1`] THEN
  ASM_SIMP_TAC[VE_POP_PUSH1]);;

let VE_UNB_NOMATCH = prove
 (`!tt n s. (!i. i < ve_cnt s ==> ~(ve_rbirth (ve_slots s i) = tt)) ==> ve_unb tt n s = s`,
  GEN_TAC THEN INDUCT_TAC THEN REWRITE_TAC[ve_unb] THEN REPEAT STRIP_TAC THEN
  COND_CASES_TAC THEN REWRITE_TAC[] THEN
  ASM_MESON_TAC[ARITH_RULE `0 < c ==> c - 1 < c`]);;

