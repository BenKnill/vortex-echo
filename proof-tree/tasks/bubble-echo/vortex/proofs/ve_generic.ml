  ASM_REWRITE_TAC[ve_punct; ve_unpunct; LET_DEF; LET_END_DEF] THEN VE_BETA_TAC THEN
  ASM_REWRITE_TAC[VE_W_ACC; ve_pop_zero] THEN STRIP_TAC THEN
  GEN_REWRITE_TAC RAND_CONV [GSYM VE_W_ETA] THEN ASM_REWRITE_TAC[]);;

let VE_COMPOSE_RULE th =
  REWRITE_RULE[] (CONV_RULE(TOP_DEPTH_CONV BETA_CONV)
   (REWRITE_RULE[FST; SND] (CONV_RULE(TOP_DEPTH_CONV BETA_CONV)
     (REWRITE_RULE[ALL; ve_run; ve_unrun; ve_runok] th))));;

let VE_STEP_INVERSE_MODEL = prove
 (parse_term ve_spec_VE_STEP_INVERSE_MODEL,
  REPEAT GEN_TAC THEN REWRITE_TAC[ve_step_ok] THEN STRIP_TAC THEN
  REWRITE_TAC[ve_step_fwd] THEN ASM_CASES_TAC `ve_pt s <= ve_t s` THEN ASM_REWRITE_TAC[] THENL
   [REWRITE_TAC[ve_step_bwd; VE_FRAME_TP; ARITH_RULE `~(n + 1 = 0)`] THEN
    SUBGOAL_THEN `ve_pt s < ve_t s + 1` (fun th -> REWRITE_TAC[th]) THENL [ASM_ARITH_TAC; ALL_TAC] THEN
    MATCH_MP_TAC(VE_COMPOSE_RULE(ISPEC
     `[ve_rim_fwd fr,ve_rim_bwd fr,(\x. T);
       ve_jig_fwd kj dj,ve_jig_bwd kj dj,(\x. T);
       ve_corr_fwd kc dc nc,ve_corr_bwd kc dc nc,(\x. T);
