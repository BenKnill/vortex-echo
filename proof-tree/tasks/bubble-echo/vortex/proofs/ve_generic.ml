let VE_KD_DMASK = prove
 (`!c K D q p m. 3 * c <= m
     ==> FST (ve_kd_fwd (ve_dmask c K) (ve_dmask c D) (q,p)) m = q m /\
         SND (ve_kd_fwd (ve_dmask c K) (ve_dmask c D) (q,p)) m = p m`,
  REPEAT GEN_TAC THEN DISCH_TAC THEN
  SUBGOAL_THEN `~(m < 3 * c)` ASSUME_TAC THENL [ASM_ARITH_TAC; ALL_TAC] THEN
  REWRITE_TAC[ve_kd_fwd; ve_dmask; LET_DEF; LET_END_DEF] THEN VE_BETA_TAC THEN
  REWRITE_TAC[FST; SND] THEN VE_BETA_TAC THEN ASM_REWRITE_TAC[WORD_ADD_0]);;

